/** Drawn from the table above; every other provider has a component of its own below. */
const isMarked = (
  provider: TextModelProviderId,
): provider is keyof typeof PROVIDER_MARKS => provider in PROVIDER_MARKS;

export function ProviderIcon({
  className,
  provider,
}: {
  provider: TextModelProviderId;
  className?: string;
}) {
  if (isMarked(provider))
    return (
      <svg
        viewBox="0 0 24 24"
        fill="currentColor"
        fillRule="evenodd"
        className={className}
        aria-hidden="true"
      >
        {PROVIDER_MARKS[provider].map((path) => (
          <path key={path.d} d={path.d} />
        ))}
      </svg>
    );
  const Icon = getIconByProvider(provider);
  return <Icon className={className} />;
}

const getIconByProvider = (
  provider: Exclude<TextModelProviderId, keyof typeof PROVIDER_MARKS>,
): FC<{ className?: string }> => {
  switch (provider) {
    case "anthropic":
      return ClaudeIcon;
    case "google":
      return GoogleIcon;
    case "openai":
    case "chatgpt":
      return OpenAIIcon;
    case "vercel-ai-gateway":
      return VercelIcon;
    case "xai":
      return GrokIcon;
  }
};
